/** Minimal HTML entity escaping for user content interpolated into markup —
 *  answers and questions travel through the embed page and oEmbed payloads. */
export function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
